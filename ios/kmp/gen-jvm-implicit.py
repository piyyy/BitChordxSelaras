# Packages that subclass LinkedHashMap as an LRU (accessOrder + removeEldestEntry), which
# Kotlin/Native's final LinkedHashMap can't do: they get a same-package stand-in.
LRU = {"com.music.bitchord.data.lyrics", "com.music.bitchord.ui.theme", "com.music.bitchord.ui.player"}
LRU_CLASS = '''
internal open class LinkedHashMap<K, V>(initialCapacity: Int = 16, loadFactor: Float = 0.75f, private val accessOrder: Boolean = false) :
    AbstractMutableMap<K, V>() {{
    constructor(from: Map<out K, V>) : this() {{ putAll(from) }}
    private val map = kotlin.collections.LinkedHashMap<K, V>()
    protected open fun removeEldestEntry(eldest: Map.Entry<K, V>): Boolean = false
    override val entries: MutableSet<MutableMap.MutableEntry<K, V>> get() = map.entries
    override fun get(key: K): V? {{
        val v = map[key]
        if (accessOrder && v != null) {{ map.remove(key); map[key] = v }}
        return v
    }}
    override fun put(key: K, value: V): V? {{
        val old = map.remove(key)
        map[key] = value
        val eldest = map.entries.firstOrNull()
        if (eldest != null && removeEldestEntry(eldest)) map.remove(eldest.key)
        return old
    }}
    override fun remove(key: K): V? = map.remove(key)
    override fun containsKey(key: K): Boolean = map.containsKey(key)
}}
'''

EXCLUDED = re.compile(r"/(kizzy|smart|potoken|presence|selaras)/|/data/Http\.kt$|/innertube/(InnerTubeXResolver|PlayerClient|StreamResolver)\.kt$|/lyrics/(Genius|TtmlLyrics|LyricsTranslation)\.kt$")

# Where each module's iOS build keeps them: the source set that compiles jvmSharedMain.
TARGET_DIR = {"shared": "src/iosMain/kotlin", "sharedUi": "src/iosShared/kotlin", "selarasUi": "src/iosShared/kotlin"}
SOURCES = ["src/jvmSharedMain/kotlin", "src/commonMain/kotlin", "src/jvmMain/kotlin"]

for module in sys.argv[1:] or ["shared"]:
    packages = set()
    files = [f for d in SOURCES if module != "shared" or d != "src/jvmMain/kotlin" for f in (ROOT / module / d).rglob("*.kt")]
    for f in files:
        if EXCLUDED.search(str(f)):
            continue
        m = re.search(r"^package\s+([\w.]+)", f.read_text(), re.M)
        if m:
            packages.add(m.group(1))
    for pkg in sorted(packages):
        out = ROOT / module / TARGET_DIR[module] / pkg.replace(".", "/") / "JvmImplicit.kt"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(TEMPLATE.format(pkg=pkg) + (LRU_CLASS.format() if pkg in LRU else ""))
        print(out.relative_to(ROOT))

#!/usr/bin/env python3
"""Writes JvmImplicit.kt into every package of a module's jvmSharedMain that the iOS build compiles.

On the JVM, java.lang.* and kotlin.jvm.* need no import (System, Character, @Volatile, synchronized,
String.format...). BitChord's upstream sources rely on that, and they must compile unchanged for
iOS, so each package gets same-package stand-ins pointing at com.music.bitchord.ioscompat.

    python3 ios/kmp/gen-jvm-implicit.py shared sharedUi selarasUi
"""

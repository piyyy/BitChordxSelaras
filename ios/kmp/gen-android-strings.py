#!/usr/bin/env python3
"""Carries the phone app's string resources (app/src/main/res/values*/strings.xml) to iOS.

The Android UI files the iOS build compiles unchanged call `stringResource(R.string.x)`. This writes

  iosApp/src/iosMain/kotlin/com/music/bitchord/R.kt     R.string / R.plurals ids + their names
  ios/App/Resources/AndroidStrings/android-strings-<tag>.json   one table per Android locale

and `androidx.compose.ui.res.stringResource` on iOS (iosApp) looks the id up in the table for the
device's language, falling back to the default (English) one — what Android itself does.

    python3 ios/kmp/gen-android-strings.py
"""
import json, pathlib, re, xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"
OUT_KT = ROOT / "iosApp/src/iosMain/kotlin/com/music/bitchord/R.kt"
OUT_JSON = ROOT / "ios/App/Resources/AndroidStrings"

KEYWORDS = {"as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
            "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
            "typeof", "val", "var", "when", "while"}


def text_of(el):
    """An element's text with inner markup (<b>, <xliff:g>…) flattened, then Android-unescaped."""
    raw = "".join(el.itertext())
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == '"' and raw[-1] == '"':
        raw = raw[1:-1]
    else:
        raw = re.sub(r"\s+", " ", raw)
    out, i = [], 0
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            n = raw[i + 1]
            out.append({"n": "\n", "t": "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def parse(path):
    strings, plurals = {}, {}
    if not path.exists():
        return strings, plurals
    root = ET.parse(path).getroot()
    for el in root:
        name = el.get("name")
        if el.tag == "string" and name:
            strings[name] = text_of(el)
        elif el.tag == "plurals" and name:
            plurals[name] = {item.get("quantity"): text_of(item) for item in el if item.tag == "item"}
    return strings, plurals


def resolve_refs(strings, fallback):
    for k, v in list(strings.items()):
        m = re.fullmatch(r"@string/(\w+)", v)
        if m:
            strings[k] = strings.get(m.group(1), fallback.get(m.group(1), v))


default_s, default_p = parse(RES / "values/strings.xml")
resolve_refs(default_s, default_s)
string_names = sorted(default_s)
plural_names = sorted(default_p)

OUT_JSON.mkdir(parents=True, exist_ok=True)
for old in OUT_JSON.glob("android-strings-*.json"):
    old.unlink()
for d in sorted(RES.glob("values*")):
    s, p = parse(d / "strings.xml")
    if not s and not p:
        continue
    resolve_refs(s, default_s)
    qualifier = d.name[len("values"):].lstrip("-") or "default"
    # Only what the default table declares — the ids are its names.
    table = {"s": {k: v for k, v in s.items() if k in default_s},
             "p": {k: v for k, v in p.items() if k in default_p}}
    (OUT_JSON / f"android-strings-{qualifier}.json").write_text(json.dumps(table, ensure_ascii=False, separators=(",", ":")))
    print(f"{qualifier}: {len(table['s'])} strings, {len(table['p'])} plurals")


def ident(n):
    return f"`{n}`" if n in KEYWORDS else n


lines = [
    "// Generated by ios/kmp/gen-android-strings.py from app/src/main/res — do not edit.",
    '@file:Suppress("unused", "ObjectPropertyName")',
    "",
    "package com.music.bitchord",
    "",
    "/** The phone app's resource ids, for the Android UI code the iOS build compiles unchanged. */",
    "object R {",
    "    object string {",
]
lines += [f"        const val {ident(n)} = {i}" for i, n in enumerate(string_names)]
lines += ["    }", "", "    object plurals {"]
lines += [f"        const val {ident(n)} = {i}" for i, n in enumerate(plural_names)]
lines += ["    }", "}", ""]
lines += ["internal val androidStringNames: Array<String> = arrayOf("]
lines += [f'    "{n}",' for n in string_names]
lines += [")", "", "internal val androidPluralNames: Array<String> = arrayOf("]
lines += [f'    "{n}",' for n in plural_names]
lines += [")", ""]
OUT_KT.parent.mkdir(parents=True, exist_ok=True)
OUT_KT.write_text("\n".join(lines))
print(OUT_KT.relative_to(ROOT), len(string_names), "strings,", len(plural_names), "plurals")

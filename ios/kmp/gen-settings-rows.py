def declaration(text: str, name: str) -> str:
    """The top-level declaration called [name], with the annotation lines right above it."""
    m = re.search(rf"^(?:(?:internal|private) )?(val|fun) {re.escape(name)}\b", text, re.M)
    if not m:
        raise SystemExit(f"{name} not found in {SRC.name}")
    is_fun = m.group(1) == "fun"
    lines = text[: m.start()].split("\n")[:-1]  # complete lines before the declaration
    annotations = []
    while lines and lines[-1].strip().startswith("@"):
        annotations.insert(0, lines.pop())
    body = text[m.start():]
    if is_fun:
        end = re.search(r"^\}\s*$", body, re.M)
        body = body[: end.end()]
    else:
        body = body.split("\n", 1)[0]
    return "\n".join(annotations + [body.rstrip()]) + "\n"


